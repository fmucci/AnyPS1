#!/usr/bin/env python3
"""Generate and compile every executable of game/game.json plus the runtime into one program: build/ps1_game (and with --frontend the SDL2 player build/ps1_play).
usage: python3 -I tools/recomp/build_game.py [-O1] [--frontend] [--calltrace]      [--coverage]     then:  build/ps1_game DISC.bin --ticks 3000 --ppm out.ppm
Writes build/game/game_config.h (names the C side needs: modules to link, boot file names, window title, card file name)."""
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))     # -I does not add the script directory
import hostenv
import gamecfg

ROOT = gamecfg.ROOT
OUT = os.environ.get("PS1_GAME_OUT", "ps1_game")


def cstr(s):
    return json.dumps(s)


def write_config(bd, overlays):
    L = ["/* generated by tools/recomp/build_game.py from game/game.json: do not edit */"]
    for _exe, pre in gamecfg.EXES:
        L.append("void gen_code_%s(void); void gen_hooks_%s(void); void gen_register_%s(void);" % (pre, pre, pre))
    first = gamecfg.EXES[0]
    L.append("void rt_hle_add_module(const char *name, void (*code)(void), void (*hooks)(void), void (*reg)(void));")
    L.append("static void game_link_modules(void) {       /* the boot executable is linked directly; every other executable is a module the program loads by name (chain titles) */")
    for exe, p in gamecfg.EXES[1:]:
        L.append("    rt_hle_add_module(%s, gen_code_%s, gen_hooks_%s, gen_register_%s);" % (cstr(exe), p, p, p))
    L.append("    gen_code_%s(); gen_hooks_%s(); gen_register_%s();" % (first[1], first[1], first[1]))
    L.append("}")
    L.append("static const char *const GAME_BOOT_NAMES[] = {" + ", ".join(cstr("\\" + n + ";1") for n in gamecfg.BOOT_NAMES) + "};")
    L.append("#define GAME_N_BOOT %d" % len(gamecfg.BOOT_NAMES))
    L.append("#define GAME_MAIN_EXE %s" % cstr(gamecfg.MAIN_EXE))
    L.append("#define GAME_TITLE %s" % cstr(gamecfg.TITLE))
    L.append("#define GAME_CARD_FILE %s" % cstr(gamecfg.NAME + ".mcr"))
    L.append("static void game_low_ram(Cpu *c) { (void)c;")
    for lo, hi, why in gamecfg.LOW_RAM:
        L.append("    rt_allow_low_ram(c, 0x%X, 0x%X, %s);" % (lo, hi, cstr(why)))
    L.append("}")
    open(os.path.join(bd, "game_config.h"), "w").write("\n".join(L) + "\n")


def main():
    opt = "-O1"
    extra = []
    for a in sys.argv[1:]:
        if a.startswith("-O"):
            opt = a
        if a == "--calltrace":
            extra = ["-DRT_CALLTRACE"]
        if a == "--coverage":                                          # generated functions record their entry: PS1_COVERAGE=file writes the list (tools/coverage_report.py)
            extra = ["-DRT_COVERAGE"]
    extra = extra + hostenv.extra_flags() + ["-DRT_YIELD_PERIOD=%d" % gamecfg.YIELD]
    bd = os.path.join(ROOT, "build", "game")
    os.makedirs(bd, exist_ok=True)
    write_config(bd, gamecfg.OVERLAYS)
    inc = ["-I", os.path.join(ROOT, "runtime"), "-I", bd]
    objs = []
    for exe, pre in gamecfg.EXES:
        out = os.path.join(bd, "gen_%s.c" % pre)
        subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools/recomp/gen.py"), os.path.join(gamecfg.DISC_DIR, exe), out, "--prefix", pre, "--hooks", "--auto-roots"], check=True)
        obj = out[:-2] + ".o"
        subprocess.run([hostenv.CC, "-std=gnu11", opt, "-w"] + extra + inc + ["-c", out, "-o", obj], check=True)
        objs.append(obj)
    # relocatable modules (overlays) listed in game/game.json: relocated by tools/recomp/exr.py at the base given there (empty for most titles)
    ov_src = ['#include <stdint.h>', '#include "cpu.h"', '#include "rt.h"']
    ov_reg = []
    for ov in gamecfg.OVERLAYS:
        name, base = ov["name"], int(ov["base"], 16)
        pre = "ovl_" + name
        exe = os.path.join(bd, pre + ".exe")
        out = subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools/recomp/exr.py"), os.path.join(gamecfg.DISC_DIR, ov["exr"]), os.path.join(gamecfg.DISC_DIR, ov["host_exe"]), ov["base"], exe, ov["relocator"]] + ([ov["scratch"]] if "scratch" in ov else []), check=True, capture_output=True, text=True).stdout
        size = int(out.rsplit("run-time size", 1)[1])
        cfile = os.path.join(bd, "gen_%s.c" % pre)
        subprocess.run([sys.executable, "-I", os.path.join(ROOT, "tools/recomp/gen.py"), exe, cfile, "--prefix", pre, "--hooks"], check=True)
        obj = cfile[:-2] + ".o"
        subprocess.run([hostenv.CC, "-std=gnu11", opt, "-w"] + extra + inc + ["-c", cfile, "-o", obj], check=True)
        objs.append(obj)
        ov_src += ["void gen_code_%s(void); void gen_hooks_%s(void); void gen_register_%s(void); int gen_check_%s(Cpu *c);" % ((pre,) * 4)]
        ov_reg.append('    rt_overlay_add("%s", %su, %d, gen_code_%s, gen_hooks_%s, gen_register_%s, gen_check_%s);' % (name, base, size, pre, pre, pre, pre))
    ov_src += ["void game_overlays(void) {"] + ov_reg + ["}"]
    ovc = os.path.join(bd, "overlays.c")
    open(ovc, "w").write("\n".join(ov_src) + "\n")
    obj = ovc[:-2] + ".o"
    subprocess.run([hostenv.CC, "-std=gnu11", opt, "-w"] + inc + ["-c", ovc, "-o", obj], check=True)
    objs.append(obj)
    rt = [os.path.join(ROOT, "runtime", f) for f in ("mem.c", "sys.c", "dispatch.c", "disc.c", "sectors.c", "trace.c", "hle.c", "io.c", "gte.c", "card.c", "interp.c")]
    subprocess.run([hostenv.CC, "-std=gnu11", opt, "-w"] + extra + inc + [os.path.join(ROOT, "tests/runtime/run_game.c")] + rt + objs +
                   ["-o", os.path.join(ROOT, "build", hostenv.exe(OUT))], check=True)
    print("built build/%s" % OUT)
    if "--frontend" in sys.argv:                                  # the SDL2 player (needs `sdl2-config`)
        sdl = hostenv.sdl_flags()
        if sdl is None: sys.exit("SDL2 not found: install it (sdl2-config / pkg-config sdl2) or set PS1_SDL_FLAGS")
        subprocess.run([hostenv.CC, "-std=gnu11", opt, "-w"] + extra + inc + [os.path.join(ROOT, "frontend/ps1_play.c")] + rt + objs + sdl +
                       ["-o", os.path.join(ROOT, "build", hostenv.exe("ps1_play"))], check=True)
        print("built build/ps1_play")


if __name__ == "__main__":
    main()
